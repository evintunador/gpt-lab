import torch
import torch.nn as nn


def run_training(
    model: nn.Module,
    optimizer: torch.optim.Optimizer,
    train_loader,
    *,
    # grad accum knobs
    accum_steps: int = 1,
    # loss tracking knobs
    track_loss: bool = False,
    log_interval: int = 1,
    # misc
    **kwargs,
) -> Dict[str, Any]:
    """Training loop with gradient accumulation and loss tracking."""
    model.train()
    optimizer.zero_grad(set_to_none=True)

    if accum_steps is None or accum_steps < 1:
        accum_steps = 1

    train_loss_history: List[float] = []
    step_count = 0
    micro_idx = 0
    
    for batch in train_loader:
        loss = model(batch)

        if accum_steps > 1:
            loss = loss / float(accum_steps)

        loss.backward()
        micro_idx += 1

        # Track loss if enabled - track based on optimizer steps, not micro-batches
        if micro_idx % accum_steps == 0:
            if track_loss and (step_count % log_interval == 0):
                # Scale loss back up for logging if it was divided for accumulation
                loss_to_log = loss.detach().cpu().item()
                if accum_steps > 1:
                    loss_to_log = loss_to_log * float(accum_steps)
                train_loss_history.append(loss_to_log)
            
            optimizer.step()
            optimizer.zero_grad(set_to_none=True)
            step_count += 1

    # Handle case where last accumulation window is incomplete
    if micro_idx % accum_steps != 0:
        # For incomplete accumulation window, we still track loss if enabled
        if track_loss and (step_count % log_interval == 0):
            # Scale loss back up for logging if it was divided for accumulation
            loss_to_log = loss.detach().cpu().item()
            if accum_steps > 1:
                loss_to_log = loss_to_log * float(accum_steps)
            train_loss_history.append(loss_to_log)
            
        optimizer.step()
        optimizer.zero_grad(set_to_none=True)
        step_count += 1

    result = {"model": model}
    if track_loss:
        result["train_loss_history"] = train_loss_history
    
    return result